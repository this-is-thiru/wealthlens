-- W-337e (D-949): assets, transactions, trade_outcomes, profit_and_loss.
-- Opaque, never-queried-into trees (corporate-action copies, the realised-profits hierarchy, order-time
-- quantities, the asset_request redrive snapshot, and the two scalar lot-linkage lists) are stored as
-- TEXT JSON columns via an AttributeConverter (C2a/C3a/C4a), same pattern as brokercharges' rules_json.

CREATE TABLE assets (
    id                          VARCHAR(255)     PRIMARY KEY,
    email                       TEXT             NOT NULL,
    stock_code                  TEXT,
    stock_name                  TEXT,
    exchange_name               TEXT,
    broker_name                 TEXT,
    price                       DOUBLE PRECISION NOT NULL DEFAULT 0,
    quantity                    DOUBLE PRECISION,
    asset_type                  TEXT,
    segment                     TEXT             NOT NULL DEFAULT 'DELIVERY',
    broker_charges              DOUBLE PRECISION NOT NULL DEFAULT 0,
    misc_charges                DOUBLE PRECISION NOT NULL DEFAULT 0,
    allocated_buy_charges       DOUBLE PRECISION NOT NULL DEFAULT 0,
    allocated_buy_misc_charges  DOUBLE PRECISION NOT NULL DEFAULT 0,
    maturity_date               DATE,
    transaction_date            DATE,
    order_id                    TEXT,
    order_execution_time        TIMESTAMPTZ(6),
    order_time_quantities_json  TEXT,
    timezone_id                 TEXT,
    account_type                TEXT,
    account_holder              TEXT,
    corporate_action            TEXT,
    transaction_type            TEXT,
    comments                    TEXT,
    buy_transaction_ids_json    TEXT,
    sell_transaction_ids_json   TEXT,
    corporate_actions_json      TEXT,
    version                     BIGINT           NOT NULL DEFAULT 0,
    created_by                  TEXT,
    updated_by                  TEXT,
    created_at                  TIMESTAMP(6),
    updated_at                  TIMESTAMP(6)
);

CREATE TABLE transactions (
    id                          VARCHAR(255)     PRIMARY KEY,
    email                       TEXT             NOT NULL,
    stock_code                  TEXT,
    stock_name                  TEXT,
    exchange_name               TEXT,
    broker_name                 TEXT,
    price                       DOUBLE PRECISION NOT NULL DEFAULT 0,
    quantity                    DOUBLE PRECISION,
    total_value                 DOUBLE PRECISION NOT NULL DEFAULT 0,
    segment                     TEXT             NOT NULL DEFAULT 'DELIVERY',
    broker_charges               DOUBLE PRECISION NOT NULL DEFAULT 0,
    misc_charges                DOUBLE PRECISION NOT NULL DEFAULT 0,
    comment                     TEXT,
    asset_type                  TEXT,
    maturity_date               DATE,
    order_id                    TEXT,
    order_execution_time        TIMESTAMP(6),
    timezone_id                 TEXT,
    account_type                TEXT,
    account_holder              TEXT,
    transaction_type            TEXT,
    transaction_date            DATE,
    corporate_action            TEXT,
    corporate_actions_json      TEXT,
    idempotency_key             TEXT,
    trade_fingerprint           TEXT,
    submitted_at                TIMESTAMP(6),
    source_temp_transaction_id  TEXT,
    status                      TEXT,
    asset_request_json          TEXT,
    trade_flow                  TEXT,
    created_by                  TEXT,
    updated_by                  TEXT,
    created_at                  TIMESTAMP(6),
    updated_at                  TIMESTAMP(6)
);
CREATE UNIQUE INDEX transaction_idempotency_key_idx ON transactions (idempotency_key) WHERE idempotency_key IS NOT NULL;
CREATE INDEX transaction_fingerprint_idx ON transactions (trade_fingerprint) WHERE trade_fingerprint IS NOT NULL;
CREATE UNIQUE INDEX transaction_source_temp_idx ON transactions (source_temp_transaction_id) WHERE source_temp_transaction_id IS NOT NULL;

CREATE TABLE trade_outcomes (
    id                              VARCHAR(255)     PRIMARY KEY,
    email                           TEXT             NOT NULL,
    stock_code                      TEXT,
    stock_name                      TEXT,
    exchange_name                   TEXT,
    broker_name                     TEXT,
    asset_type                      TEXT,
    account_type                    TEXT,
    account_holder                  TEXT,
    original_buy_price              DOUBLE PRECISION NOT NULL DEFAULT 0,
    ca_adjusted_buy_price           DOUBLE PRECISION NOT NULL DEFAULT 0,
    buy_quantity                    DOUBLE PRECISION,
    buy_date                        DATE,
    buy_broker_charges              DOUBLE PRECISION NOT NULL DEFAULT 0,
    buy_misc_charges                DOUBLE PRECISION NOT NULL DEFAULT 0,
    sell_price                      DOUBLE PRECISION NOT NULL DEFAULT 0,
    sell_quantity                   DOUBLE PRECISION,
    sell_date                       DATE,
    sell_broker_charges             DOUBLE PRECISION NOT NULL DEFAULT 0,
    sell_misc_charges               DOUBLE PRECISION NOT NULL DEFAULT 0,
    total_buy_value                 DOUBLE PRECISION NOT NULL DEFAULT 0,
    total_sell_value                DOUBLE PRECISION NOT NULL DEFAULT 0,
    net_profit                      DOUBLE PRECISION NOT NULL DEFAULT 0,
    profit_percentage               DOUBLE PRECISION NOT NULL DEFAULT 0,
    holding_period_days             BIGINT,
    segment                         TEXT,
    instrument_sub_class            TEXT,
    buy_charge_breakup_json         TEXT,
    sell_charge_breakup_json        TEXT,
    financial_year                  TEXT,
    source_sell_transaction_id      TEXT,
    source_buy_lot_id               TEXT,
    is_ca_derived                   BOOLEAN,
    applied_corporate_actions_json   TEXT,
    acquisition_mode                TEXT,
    acquisition_corporate_action    TEXT,
    buy_exchange_name               TEXT,
    buy_segment                     TEXT,
    sell_exchange_name              TEXT,
    sell_segment                    TEXT,
    created_by                      TEXT,
    updated_by                      TEXT,
    created_at                      TIMESTAMP(6),
    updated_at                      TIMESTAMP(6)
);
CREATE INDEX trade_outcome_user_idx ON trade_outcomes (email, sell_date DESC);
CREATE INDEX trade_outcome_buy_lot_idx ON trade_outcomes (email, source_buy_lot_id);

CREATE TABLE profit_and_loss (
    id                             VARCHAR(255)     PRIMARY KEY,
    email                          TEXT             NOT NULL,
    financial_year                 TEXT,
    realised_profits_json          TEXT,
    out_sourced_realised_profits_json TEXT,
    version                        BIGINT           NOT NULL DEFAULT 0,
    created_by                     TEXT,
    updated_by                     TEXT,
    created_at                     TIMESTAMP(6),
    updated_at                     TIMESTAMP(6)
);
CREATE UNIQUE INDEX pnl_user_year_idx ON profit_and_loss (email, financial_year);
