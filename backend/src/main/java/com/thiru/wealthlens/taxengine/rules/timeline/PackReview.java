package com.thiru.wealthlens.taxengine.rules.timeline;

import com.thiru.wealthlens.taxengine.rules.id.TaxYearId;
import java.util.ArrayList;
import java.util.List;
import java.util.Map;
import java.util.TreeMap;

/**
 * The review file for one pair of tax years ({@code DR 15} C4; W-139): {@link PackLint}'s findings first, then every
 * {@link PackDiff} change, one line per rule or regime entry. It is committed and compared on every build, so a change to the
 * law cannot land without this file changing in the same commit, where a reviewer reads it.
 */
public final class PackReview {

    private PackReview() {
    }

    /** The file's name for a pair, e.g. {@code pack-review-2025-26-to-2026-27.md}. */
    public static String fileName(TaxYearId from, TaxYearId to) {
        return "pack-review-" + from.label() + "-to-" + to.label() + ".md";
    }

    public static String render(CompiledPack before, CompiledPack after) {
        List<PackLint.Finding> lint = PackLint.between(before, after);
        PackDiff diff = PackDiff.between(before, after);
        StringBuilder out = new StringBuilder();
        out.append("# Pack review — TY ").append(before.taxYear().label()).append(" → TY ").append(after.taxYear().label())
                .append("\n\nGenerated by `PackReviewTest` from the shipped timeline (W-139, `DR 15` C4). Not edited by hand:")
                .append(" change the timeline, run\n`./mvnw test -pl backend -Dtest=PackReviewTest -Dpack.review.write=true`,")
                .append(" and read what changed here before committing.\n\n## To read first — ").append(lint.size())
                .append(" finding(s)\n\n");
        lint.forEach(finding -> out.append("- ").append(line(finding, before, after)).append('\n'));
        Map<String, List<String>> changes = changesBySubject(diff);
        out.append("\n## Every change — ").append(changes.size()).append(" rule(s) or regime entries\n\n");
        changes.forEach((subject, lines) -> out.append("- `").append(subject).append("`: ")
                .append(String.join("; ", lines)).append('\n'));
        return out.toString();
    }

    private static String line(PackLint.Finding finding, CompiledPack before, CompiledPack after) {
        return switch (finding) {
            case PackLint.Finding.UnexplainedDrop drop -> "**Unexplained drop** `" + drop.rule().value() + "`: in TY "
                    + before.taxYear().label() + ", not in TY " + after.taxYear().label()
                    + ", and no provision of it says the Act dropped it";
            case PackLint.Finding.CopiedVersion copy -> "**Copied version** `" + copy.rule().value() + "` " + copy.earlier()
                    + " → " + copy.later() + ": the same instrument and source as its predecessor";
            case PackLint.Finding.ShapeChanged shape -> "**Shape changed** `" + shape.rule().value() + "` " + shape.earlier()
                    + " → " + shape.later() + ": `" + shape.field() + "` " + shape.before() + " → " + shape.after();
            case PackLint.Finding.TenfoldChange tenfold -> "**Tenfold change** `" + tenfold.rule().value() + "` "
                    + tenfold.versions() + ": `" + tenfold.field() + "` " + tenfold.before() + " → " + tenfold.after();
        };
    }

    private static Map<String, List<String>> changesBySubject(PackDiff diff) {
        Map<String, List<String>> changes = new TreeMap<>();
        for (PackDiff.Finding finding : diff.findings()) {
            switch (finding) {
                case PackDiff.Finding.RuleAdded added -> add(changes, added.rule().value(), "added");
                case PackDiff.Finding.RuleRemoved removed -> add(changes, removed.rule().value(), "removed");
                case PackDiff.Finding.VersionAdded added ->
                        add(changes, added.rule().value(), "version " + added.version() + " added");
                case PackDiff.Finding.VersionRemoved removed ->
                        add(changes, removed.rule().value(), "version " + removed.version() + " removed");
                case PackDiff.Finding.ValueChanged changed -> add(changes, changed.rule().value(), changed.version() + " `"
                        + changed.field() + "` " + changed.before() + " → " + changed.after());
                case PackDiff.Finding.RegimeValueChanged changed -> add(changes, changed.entry(),
                        "`" + changed.field() + "` " + changed.before() + " → " + changed.after());
            }
        }
        return changes;
    }

    private static void add(Map<String, List<String>> changes, String subject, String change) {
        changes.computeIfAbsent(subject, key -> new ArrayList<>()).add(change);
    }
}
