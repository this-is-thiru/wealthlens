package com.thiru.wealthlens.taxplanning.workspace;

import com.fasterxml.jackson.annotation.JsonIgnore;
import com.thiru.wealthlens.shared.entity.helper.AuditColumns;
import com.thiru.wealthlens.shared.entity.model.CreatedWithId;
import com.thiru.wealthlens.shared.entity.model.CreatedWithIdSaved;
import com.thiru.wealthlens.shared.protection.EncryptedColumn;
import com.thiru.wealthlens.shared.protection.SearchableColumn;
import jakarta.persistence.Column;
import jakarta.persistence.Convert;
import jakarta.persistence.Embedded;
import jakarta.persistence.Entity;
import jakarta.persistence.EntityListeners;
import jakarta.persistence.Id;
import jakarta.persistence.Table;
import jakarta.persistence.Transient;
import lombok.Data;
import lombok.NoArgsConstructor;
import org.springframework.data.jpa.domain.support.AuditingEntityListener;

/**
 * One accepted save: append-only, and no method here or in its service updates or deletes one ({@code DR 11} F2). Revision nil holds
 * the full state and later ones a patch, so any state can be replayed; the unique key is what stops two saves of one revision.
 */
@Entity
@Table(name = "tax_draft_revisions")
@EntityListeners({AuditingEntityListener.class, CreatedWithIdSaved.class})
@Data
@NoArgsConstructor
public class DraftRevision implements CreatedWithId {

    @Id
    private String id;

    @Column(name = "draft_id")
    private String draftId;

    @Column(name = "revision_number")
    private int revisionNumber;

    @Convert(converter = EncryptedColumn.class)
    @Column(name = "full_state_json")
    private String fullStateJson;

    @Convert(converter = EncryptedColumn.class)
    @Column(name = "change_set_json")
    private String changeSetJson;

    @Convert(converter = SearchableColumn.class)
    @Column(name = "changed_by")
    private String changedBy;

    /** Whether this edit took a {@code READY} draft back to {@code DRAFT}. */
    @Column(name = "reopened")
    private boolean reopened;

    /** Where the change came from, if a salary workbook (W-133b); none for every other save, and for every save before W-133b. */
    @Convert(converter = WorkbookImportConverter.class)
    @Column(name = "imported_from")
    private WorkbookImport importedFrom;

    /**
     * {@code importedFrom.workbookSha256}, denormalized out of the opaque JSON column (W-337f, D-951): the one field
     * {@code DraftRevisionRepository.findFirstByDraftIdAndImportedFromWorkbookSha256} actually queries, and a
     * {@code @Convert}-mapped attribute is opaque to Spring Data JPA's derived-query property-path resolution. Kept
     * in step by {@link #setImportedFrom} below, not generated by {@code @Data} — this class defines that setter
     * itself.
     */
    @Column(name = "imported_from_workbook_sha256")
    private String importedFromWorkbookSha256;

    public void setImportedFrom(WorkbookImport importedFrom) {
        this.importedFrom = importedFrom;
        this.importedFromWorkbookSha256 = importedFrom == null ? null : importedFrom.getWorkbookSha256();
    }

    @Embedded
    private AuditColumns auditMetadata = new AuditColumns();

    /** Whether this instance is not yet stored (W-329b): never stored, never read back. */
    @Transient
    @JsonIgnore
    private boolean newlyCreated;

    @Override
    public boolean isNew() {
        return newlyCreated || id == null;
    }
}
